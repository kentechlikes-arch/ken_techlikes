/**
 * Safaricom Lipa Na M-Pesa Buy Goods SMS Security Parser & Anti-Fraud Validator
 * Designed strictly to detect edited, forged, or duplicate M-Pesa messages.
 */

import { doc, getDoc, setDoc } from 'firebase/firestore';
import { db, auth } from './firebase';

export interface MpesaVerificationResult {
  isValid: boolean;
  code?: string;
  amount?: number;
  recipient?: string;
  dateTime?: string;
  newBalance?: number;
  transactionCost?: number;
  error?: string;
  securityFlags?: string[];
  rawText?: string;
}

const TILL_NUMBER = '1856074';
const VALID_RECIPIENT_KEYWORDS = [
  '1856074',
  'KEN_TECH LIKES',
  'KEN TECH LIKES',
  'KENTECH LIKES',
  'KENTECH',
  'KEN_TECH',
  'KEN TECH'
];

// Obvious dummy codes often generated by fake SMS apps
const BLACKLISTED_CODES = new Set([
  'AAAAAAAAAA',
  '0000000000',
  '1234567890',
  'QWERTYUIOP',
  'TEST123456',
  'SAMPLECODE',
  'MPESA12345',
  'DEMO123456'
]);

/**
 * Validates and extracts details from a raw Safaricom M-Pesa SMS message.
 * Enforces anti-tamper, date freshness, recipient matching, and structural checks.
 */
export function parseAndValidateMpesaMessage(rawMessage: string, expectedTill: string = TILL_NUMBER): MpesaVerificationResult {
  if (!rawMessage || typeof rawMessage !== 'string') {
    return {
      isValid: false,
      error: 'Please paste your complete Safaricom M-Pesa confirmation SMS.',
    };
  }

  // 1. Check for invisible / zero-width characters often used by fraud scripts
  const zeroWidthRegex = /[\u200B-\u200D\uFEFF]/g;
  if (zeroWidthRegex.test(rawMessage)) {
    return {
      isValid: false,
      error: 'Security Violation: Hidden zero-width or spoofing characters detected in the message.',
      securityFlags: ['ZERO_WIDTH_CHARS_DETECTED']
    };
  }

  const cleanText = rawMessage.trim().replace(/\r\n/g, ' ').replace(/\n/g, ' ').replace(/\s+/g, ' ');

  // 2. Minimum length check - An authentic Safaricom receipt is at least 90 characters
  if (cleanText.length < 70) {
    return {
      isValid: false,
      error: 'Incomplete Message: The text is too short to be an authentic Safaricom M-Pesa confirmation. Please paste the entire SMS.',
    };
  }

  // 3. Extract and validate Transaction Reference Code (Must start at the very beginning)
  // Example: "TD982341KA Confirmed." or "QJD78239KA Confirmed."
  const codeRegex = /^([A-Z0-9]{10})\s+(?:Confirmed|confirmed)\.?/i;
  const codeMatch = cleanText.match(codeRegex);

  if (!codeMatch) {
    return {
      isValid: false,
      error: 'Invalid Format: Authentic Safaricom SMS must begin with a 10-character reference code followed by "Confirmed." (e.g. TD982341KA Confirmed.)',
    };
  }

  const code = codeMatch[1].toUpperCase();

  // Validate Code structure (Safaricom reference codes are strictly 10 alphanumeric characters)
  if (BLACKLISTED_CODES.has(code) || /^([A-Z0-9])\1{9}$/.test(code)) {
    return {
      isValid: false,
      error: `Fraud Alert: Reference code ${code} is recognized as an invalid test/dummy code.`,
      securityFlags: ['BLACKLISTED_CODE']
    };
  }

  // Safaricom codes start with a letter (e.g. S, T, R, Q)
  if (!/^[A-Z][A-Z0-9]{9}$/.test(code)) {
    return {
      isValid: false,
      error: `Invalid Reference Code: "${code}" does not conform to official Safaricom 10-digit transaction standards.`,
      securityFlags: ['NON_CONFORMING_CODE']
    };
  }

  // 4. Structural Integrity Checks - Must contain standard Safaricom keywords
  const requiredTokens = [
    { token: /paid to|sent to/i, name: 'paid to / sent to' },
    { token: /on\s+\d{1,2}\/\d{1,2}\/\d{2,4}/i, name: 'date ("on DD/MM/YY")' },
    { token: /at\s+\d{1,2}:\d{2}\s*(?:AM|PM)/i, name: 'time ("at H:MM AM/PM")' },
    { token: /New M-PESA balance/i, name: 'New M-PESA balance' },
  ];

  for (const { token, name } of requiredTokens) {
    if (!token.test(cleanText)) {
      return {
        isValid: false,
        error: `Tampered Message: Missing standard Safaricom security token: [${name}]. Please paste the original unedited message directly from Safaricom.`,
        securityFlags: ['MISSING_STRUCTURAL_TOKEN']
      };
    }
  }

  // 5. Recipient Verification
  // The message must state payment to Till 1856074 or KEN_TECH LIKES
  const recipientSegmentMatch = cleanText.match(/(?:paid to|sent to)\s+([^.]+?)\s+on\s+\d/i);
  if (!recipientSegmentMatch) {
    return {
      isValid: false,
      error: 'Message parsing failed: Unable to verify recipient details. Do not edit the message text.',
    };
  }

  const recipientText = recipientSegmentMatch[1].toUpperCase();
  const hasExpectedTill = recipientText.includes(expectedTill) || cleanText.includes(expectedTill);
  const hasMerchantName = VALID_RECIPIENT_KEYWORDS.some(kw => recipientText.includes(kw));

  if (!hasExpectedTill && !hasMerchantName) {
    return {
      isValid: false,
      error: `Recipient Mismatch: This M-Pesa payment was addressed to "${recipientSegmentMatch[1].trim()}", NOT Buy Goods Till ${expectedTill} (KEN_TECH LIKES). Payments to other accounts cannot be credited.`,
      securityFlags: ['WRONG_RECIPIENT']
    };
  }

  // 6. Extract Amount (Safaricom format: "Ksh1,500.00" or "Ksh 1,500.00")
  const amountRegex = /Ksh\s*([0-9,]+(?:\.[0-9]{2})?)/i;
  const amountMatch = cleanText.match(amountRegex);

  if (!amountMatch) {
    return {
      isValid: false,
      error: 'Amount not found: Unable to extract paid amount from the SMS.',
    };
  }

  const rawAmountStr = amountMatch[1].replace(/,/g, '');
  const amount = parseFloat(rawAmountStr);

  if (isNaN(amount) || amount <= 0) {
    return {
      isValid: false,
      error: 'Invalid Amount: The amount extracted from the message is invalid.',
      securityFlags: ['INVALID_AMOUNT']
    };
  }

  if (amount < 50) {
    return {
      isValid: false,
      error: `Minimum Deposit: The payment amount (KES ${amount}) is below the minimum allowed deposit of KES 50.`,
    };
  }

  // 7. Date & Time Freshness Validation
  // Safaricom format: "on 27/10/26 at 10:45 AM" or "on 27/10/2026 at 10:45 AM"
  const dateTimeRegex = /on\s+(\d{1,2})\/(\d{1,2})\/(\d{2,4})\s+at\s+(\d{1,2}):(\d{2})\s*(AM|PM)/i;
  const dateMatch = cleanText.match(dateTimeRegex);

  if (!dateMatch) {
    return {
      isValid: false,
      error: 'Invalid Date/Time: Unable to parse transaction timestamp.',
      securityFlags: ['DATE_PARSING_FAILED']
    };
  }

  const day = parseInt(dateMatch[1], 10);
  const month = parseInt(dateMatch[2], 10);
  let year = parseInt(dateMatch[3], 10);
  if (year < 100) {
    year += 2000;
  }

  let hours = parseInt(dateMatch[4], 10);
  const minutes = parseInt(dateMatch[5], 10);
  const meridiem = dateMatch[6].toUpperCase();

  if (meridiem === 'PM' && hours < 12) hours += 12;
  if (meridiem === 'AM' && hours === 12) hours = 0;

  // Construct message date in East Africa Time (UTC+3)
  const txnDate = new Date(Date.UTC(year, month - 1, day, hours - 3, minutes));
  const now = new Date();

  // Difference in hours
  const diffHours = (now.getTime() - txnDate.getTime()) / (1000 * 60 * 60);

  // Future check: transaction cannot be more than 2 hours in future (allowing small clock drift)
  if (diffHours < -2) {
    return {
      isValid: false,
      error: 'Fraud Alert: Transaction date is set in the future. Modified timestamps are strictly rejected.',
      securityFlags: ['FUTURE_DATE_DETECTED']
    };
  }

  // Age check: cannot be older than 48 hours
  if (diffHours > 72) {
    return {
      isValid: false,
      error: `Expired Transaction: This transaction is dated ${day}/${month}/${year}, which is older than the 48-hour verification limit. Please contact support if this was a valid recent payment.`,
      securityFlags: ['EXPIRED_TRANSACTION']
    };
  }

  // 8. Extract New Balance & Transaction Cost
  let newBalance: number | undefined;
  const balanceMatch = cleanText.match(/New M-PESA balance is Ksh\s*([0-9,]+(?:\.[0-9]{2})?)/i);
  if (balanceMatch) {
    newBalance = parseFloat(balanceMatch[1].replace(/,/g, ''));
  }

  let transactionCost = 0;
  const costMatch = cleanText.match(/Transaction cost,?\s*Ksh\s*([0-9,]+(?:\.[0-9]{2})?)/i);
  if (costMatch) {
    transactionCost = parseFloat(costMatch[1].replace(/,/g, ''));
  }

  return {
    isValid: true,
    code,
    amount,
    recipient: `Buy Goods Till ${expectedTill} (KEN_TECH LIKES)`,
    dateTime: `${day.toString().padStart(2, '0')}/${month.toString().padStart(2, '0')}/${year} at ${dateMatch[4]}:${dateMatch[5]} ${meridiem}`,
    newBalance,
    transactionCost,
    rawText: cleanText,
  };
}

/**
 * Checks Firestore and local storage to prevent replay attacks (using the same M-Pesa code twice).
 */
export async function checkMpesaCodeAlreadyClaimed(code: string): Promise<boolean> {
  const cleanCode = code.trim().toUpperCase();

  // 1. Check local storage cache first
  try {
    const localClaimed = localStorage.getItem('kentech_claimed_mpesa_codes');
    if (localClaimed) {
      const list: string[] = JSON.parse(localClaimed);
      if (list.includes(cleanCode)) {
        return true;
      }
    }
  } catch (e) {}

  // 2. Check Firestore mpesa_claims collection
  try {
    const claimDoc = await getDoc(doc(db, 'mpesa_claims', cleanCode));
    if (claimDoc.exists()) {
      return true;
    }
  } catch (err) {
    console.warn('Note checking mpesa_claims in Firestore:', err);
  }

  // 3. Check transactions collection
  try {
    const txnDoc = await getDoc(doc(db, 'transactions', cleanCode));
    if (txnDoc.exists()) {
      return true;
    }
  } catch (err) {}

  return false;
}

/**
 * Permanently locks a verified M-Pesa transaction code in Firestore to prevent any future reuse.
 */
export async function lockMpesaCodeClaim(
  code: string,
  amount: number,
  rawMessage: string,
  userId: string = 'guest'
): Promise<void> {
  const cleanCode = code.trim().toUpperCase();

  // 1. Save to local storage cache
  try {
    const localClaimed = localStorage.getItem('kentech_claimed_mpesa_codes');
    const list: string[] = localClaimed ? JSON.parse(localClaimed) : [];
    if (!list.includes(cleanCode)) {
      list.push(cleanCode);
      localStorage.setItem('kentech_claimed_mpesa_codes', JSON.stringify(list));
    }
  } catch (e) {}

  // 2. Persist claim document to Firestore
  try {
    await setDoc(doc(db, 'mpesa_claims', cleanCode), {
      code: cleanCode,
      amount,
      claimedAt: new Date().toISOString(),
      claimedBy: userId,
      userEmail: auth.currentUser?.email || 'unregistered_client',
      rawMessage,
      status: 'VERIFIED_AND_CREDITED',
    });
  } catch (error) {
    console.warn('Failed to lock mpesa_claims in Firestore:', error);
  }
}
